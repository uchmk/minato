/// A keymap `desc` in `lang`: the built-in ones have Japanese; the rest
/// (the user's own) come back as they are.
pub fn desc(lang: &str, d: &str) -> String {
    let ja = (lang == "ja").then(|| DESC_JA.iter().find(|(en, _)| *en == d)).flatten();
    ja.map_or_else(|| d.to_owned(), |(_, j)| (*j).to_owned())
}

/// The language codes minato has words for.
pub const AVAILABLE: [&str; 2] = ["en", "ja"];

/// The words for `key` in `lang` (`ja`, else English); the key itself when
/// there are none.
pub fn tr(lang: &str, key: &'static str) -> &'static str {
    let table = if lang == "ja" { JA } else { EN };
    table.iter().chain(EN).find(|(k, _)| *k == key).map_or(key, |(_, v)| v)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn both_languages_have_the_same_keys() {
        fn keys(t: &[(&'static str, &'static str)]) -> Vec<&'static str> {
            t.iter().map(|(k, _)| *k).collect()
        }
        assert_eq!(keys(EN), keys(JA));
    }

    #[test]
    fn every_built_in_desc_has_japanese() {
        for (layer, list) in crate::keymap::Keys::built_in_layers() {
            for b in list {
                assert!(!b.desc.is_empty(), "[{layer}] {}", b.raw);
                assert!(DESC_JA.iter().any(|(en, _)| *en == b.desc), "[{layer}] {}", b.desc);
                assert_eq!(desc("en", &b.desc), b.desc);
            }
        }
    }

    #[test]
    fn unknown_keys_come_back_as_they_are() {
        assert_eq!(tr("ja", "nope"), "nope");
        assert_eq!(tr("ja", "view.inbox"), "受信箱");
        assert_eq!(tr("fr", "view.inbox"), "Inbox");
    }

    #[test]
    fn the_rules_and_the_notifications_have_words() {
        let has = |k: &str| EN.iter().any(|(key, _)| *key == k);
        for rule in minato_core::inbox::RULES {
            for k in [rule.why(), rule.note(), rule.next().1, rule.todo(), rule.ask()] {
                assert!(has(k), "{k}");
            }
        }
        for reason in ["ci_activity", "review_requested", "mention", "comment", "assign", "state_change", "author", "other"] {
            let k = minato_core::notes::event(reason).0;
            assert!(has(k), "{k}");
        }
    }
}
